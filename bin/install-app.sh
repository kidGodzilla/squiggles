#!/bin/bash
# Installs ~/Applications/Agents.app (Spotlight: "Agents") and a login item that keeps the server running.
# Safe to re-run, e.g. after moving the project or changing Node.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
NODE="$(command -v node)"
CLAUDE_DIR="$(dirname "$(command -v claude)")"
PORT="$(cd "$ROOT" && "$NODE" --input-type=module -e "import { loadConfig } from './config.mjs'; console.log(loadConfig().port)")"
APP="$HOME/Applications/Agents.app"
PLIST="$HOME/Library/LaunchAgents/local.agents.server.plist"
LOG="$HOME/Library/Logs/agents.log"

# icon: the lead squiggle, drawn by the same code as the room
CHROME="/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"
TMP="$(mktemp -d)"
if [ -x "$CHROME" ]; then
  "$CHROME" --headless=new --disable-gpu --hide-scrollbars --default-background-color=00000000 --window-size=1024,1024 \
    --screenshot="$TMP/icon.png" "file://$ROOT/assets/icon.html" >/dev/null 2>&1 || true
fi
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
if [ -f "$TMP/icon.png" ]; then
  mkdir -p "$TMP/Agents.iconset"
  for s in 16 32 128 256 512; do
    sips -z $s $s "$TMP/icon.png" --out "$TMP/Agents.iconset/icon_${s}x${s}.png" >/dev/null
    sips -z $((s*2)) $((s*2)) "$TMP/icon.png" --out "$TMP/Agents.iconset/icon_${s}x${s}@2x.png" >/dev/null
  done
  iconutil -c icns "$TMP/Agents.iconset" -o "$APP/Contents/Resources/Agents.icns"
fi
rm -rf "$TMP"

cat > "$APP/Contents/Info.plist" <<PL
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>CFBundleName</key><string>Agents</string>
  <key>CFBundleDisplayName</key><string>Agents</string>
  <key>CFBundleIdentifier</key><string>local.agents.app</string>
  <key>CFBundleVersion</key><string>1.0</string>
  <key>CFBundleShortVersionString</key><string>1.0</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleExecutable</key><string>agents</string>
  <key>CFBundleIconFile</key><string>Agents</string>
  <key>LSUIElement</key><true/>
  <key>NSHighResolutionCapable</key><true/>
</dict></plist>
PL

cat > "$APP/Contents/MacOS/agents" <<SH
#!/bin/bash
# Generated by bin/install-app.sh. Opens the room; starts the server if the login item isn't running it.
PORT=$PORT
if ! curl -s -o /dev/null "http://127.0.0.1:\$PORT/api/health"; then
  launchctl kickstart "gui/\$(id -u)/local.agents.server" 2>/dev/null || \
    (cd "$ROOT" && PATH="$CLAUDE_DIR:$(dirname "$NODE"):\$PATH" nohup "$NODE" server.mjs >> "$LOG" 2>&1 &)
  for _ in \$(seq 1 40); do curl -s -o /dev/null "http://127.0.0.1:\$PORT/api/health" && break; sleep 0.25; done
fi
open "http://127.0.0.1:\$PORT"
SH
chmod +x "$APP/Contents/MacOS/agents"

cat > "$PLIST" <<PL
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>Label</key><string>local.agents.server</string>
  <key>ProgramArguments</key><array><string>$NODE</string><string>$ROOT/server.mjs</string></array>
  <key>WorkingDirectory</key><string>$ROOT</string>
  <key>EnvironmentVariables</key><dict>
    <key>PATH</key><string>$CLAUDE_DIR:$(dirname "$NODE"):/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin</string>
    <key>HOME</key><string>$HOME</string>
  </dict>
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key><true/>
  <key>ThrottleInterval</key><integer>10</integer>
  <key>StandardOutPath</key><string>$LOG</string>
  <key>StandardErrorPath</key><string>$LOG</string>
</dict></plist>
PL

launchctl bootout "gui/$(id -u)/local.agents.server" 2>/dev/null || true
launchctl bootstrap "gui/$(id -u)" "$PLIST"
touch "$APP"
echo "Installed $APP and login item local.agents.server (log: $LOG)"
