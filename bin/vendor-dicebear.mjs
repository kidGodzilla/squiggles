#!/usr/bin/env node
// Vendors a DiceBear style's Figma-exported SVG parts as a classic script: ui/gen/<name>-parts.js (t833).
// usage: node bin/vendor-dicebear.mjs <unpacked @dicebear/<style> package dir> <name>
// Reads the component files as text (never imports them), keeps only their SVG templates, and drops @dicebear/core.
// Licenses go in THIRD-PARTY-NOTICES.md: the code is MIT, the art license differs per style.
import fs from 'node:fs';
import path from 'node:path';

const [pkgDir, name] = process.argv.slice(2);
if (!pkgDir || !/^[a-z][a-z0-9]*$/.test(name || '')) { console.error('usage: vendor-dicebear.mjs <package dir> <name>'); process.exit(1); }
const pkg = JSON.parse(fs.readFileSync(path.join(pkgDir, 'package.json'), 'utf8'));
const dir = path.join(pkgDir, 'lib', 'components');
const groups = fs.readdirSync(dir).filter((f) => f.endsWith('.js') && f !== 'index.js').sort();

const body = groups.map((f) => {
  let src = fs.readFileSync(path.join(dir, f), 'utf8')
    .replace(/\/\*\*[\s\S]*?\*\/\s*/, '')
    .replace(/^import .*$/gm, '')
    .replace(/escape\.xml\(/g, 'X(')
    .trim();
  const m = src.match(/^export const (\w+) = (\{[\s\S]*\});$/);
  if (!m) throw new Error(`unexpected shape in ${f}`);
  if (/\b(import|require|fetch|eval|Function|document|window)\b/.test(m[2])) throw new Error(`unexpected code in ${f}`);
  return `  ${m[1]}: ${m[2]},`;
}).join('\n');

const out = `// Generated by bin/vendor-dicebear.mjs from ${pkg.name} ${pkg.version} (MIT; see THIRD-PARTY-NOTICES.md for the art license). Do not edit.
var DICEBEAR = (typeof DICEBEAR !== 'undefined' && DICEBEAR) || {};
DICEBEAR.${name} = (() => {
const X = (s) => String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);
return {
${body}
};
})();
`;
const dest = new URL(`../ui/gen/${name}-parts.js`, import.meta.url);
fs.mkdirSync(new URL('.', dest), { recursive: true });
fs.writeFileSync(dest, out);
console.log(`${dest.pathname}: ${groups.length} groups, ${out.length} bytes`);
